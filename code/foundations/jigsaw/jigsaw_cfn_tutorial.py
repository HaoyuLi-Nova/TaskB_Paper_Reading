"""
Jigsaw CFN 教学脚本（对应 ECCV 2016 论文图 3 / §3）

================================================================================
一整轮训练在干什么？（自监督代理任务）
================================================================================

目标：不需要 ImageNet 类别标签，只靠**把打乱的拼图还原成哪种排布**
     来逼网络学会：物体部件长什么样、部件之间怎么摆。

完整流水线：

  [离线准备]
    ① 固定一个**置换集**perm_set，大小 N（论文常用 1000，这里用 64）
       每个元素是长度为 9 的排列，例如 [2,0,1,5,3,4,8,6,7]
       含义：第 i 个网络输入槽，放原来第 perm[i] 号格子的图块

  [每个 batch / 每张图]
    ② 取一张图，裁成 3×3=9 个格子（论文：225→75×75 格，再随机取 64×64；
       本脚本简化为 96→直接切 32×32）
    ③ 从 perm_set 里随机抽一个置换，记下它的索引 y ∈ {0..N-1}
       → y 就是这张图的**免费标签**（自监督）
    ④ 按该置换打乱 9 块，得到输入 patches
    ⑤ 送进 CFN：
         9 个头共享同一份卷积权重（到 fc6）分别编码每一块
         → 拼接 9 个特征向量
         → fc7/fc8 做 N 类分类，预测**用了哪个置换**
    ⑥ cross_entropy(预测, y) → backward → 更新参数

为什么叫 Context-Free Network？
  因为前半段（stem/fc6）每个图块的感受野被强制限制在**这一块内部**——
  块与块之间不能偷看边缘连续性等低层捷径；只有最后的全连接才看全局排布。
"""

import torch
import torch.nn as nn
import torch.nn.functional as F

# 置换集大小：论文消融里 N=1000、平均 Hamming≈8 时迁移最好；演示用小一点
N_PERM = 64


# =============================================================================
# 1. 共享骨干 TinyStem ≈ 论文 CFN 的**一行**（AlexNet 到 fc6）
# =============================================================================
class TinyStem(nn.Module):
    """
    论文：每一行是共享权重的 AlexNet，输出到 fc6（512 维）。
    这里：几层卷积压成 32 维，只保留**单块 → 特征向量**这一语义。

    输入:  (B, 3, H, W)  单块图块
    输出:  (B, feat_dim) 该块的外观特征 F_i
    """

    def __init__(self, feat_dim=32):
        super().__init__()
        self.net = nn.Sequential(
            # 卷积只看当前这一块内部像素 —— 这就是 "context-free" 的来源
            nn.Conv2d(3, 16, 5, stride=2), nn.ReLU(),
            nn.Conv2d(16, 32, 3, stride=2), nn.ReLU(),
            nn.AdaptiveAvgPool2d(1),          # → (B, 32, 1, 1)
            nn.Flatten(),                    # → (B, 32)
            nn.Linear(32, feat_dim), nn.ReLU(),  # ≈ 论文的 fc6
        )

    def forward(self, x):
        return self.net(x)


# =============================================================================
# 2. CFN：孪生九头 + 晚融合分类头
# =============================================================================
class CFN(nn.Module):
    """
    结构（对照论文图 3）：

        patch0 ──► stem ──► f0 ─┐
        patch1 ──► stem ──► f1 ─┤
          ...                   ├─ concat ─► fc7 ─► fc8 ─► logits (N 类)
        patch8 ──► stem ──► f8 ─┘
                   ▲
                   └── 九个头共用同一份 stem 权重（siamese-ennead）

    输出不是**每块该去哪**，而是**整盘拼图对应置换集里的哪一个索引**。
    """

    def __init__(self, feat_dim=32, n_perm=N_PERM):
        super().__init__()
        # 只实例化一份 stem：九次前向共享参数，反传时梯度会累加到同一份权重上
        self.stem = TinyStem(feat_dim)
        # 晚融合：9 个块特征拼在一起后，才第一次出现**跨块上下文**
        self.fc7 = nn.Sequential(nn.Linear(9 * feat_dim, 64), nn.ReLU())
        # 分类头：N 个置换 = N 类
        self.fc8 = nn.Linear(64, n_perm)

    def forward(self, patches):
        """
        patches: (B, 9, 3, H, W)
                 第 b 张图、第 i 个**输入槽**上的图块
                 （已经按某个置换打乱过，槽位顺序 ≠ 原图格子顺序）
        return:  (B, n_perm)  每个置换的未归一化分数（logits）
        """
        # ---- 阶段 A：九头独立编码（无跨块交互）----
        # patches[:, i] 形状 (B, 3, H, W)；循环 9 次，每次走同一个 stem
        feats = [self.stem(patches[:, i]) for i in range(9)]  # 列表里 9 个 (B, feat_dim)

        # ---- 阶段 B：拼接 → 第一次看到全局排布 ----
        x = torch.cat(feats, dim=1)  # (B, 9 * feat_dim)

        # ---- 阶段 C：预测置换索引 ----
        return self.fc8(self.fc7(x))  # (B, n_perm)


# =============================================================================
# 3. 数据构造：切 3×3 + 按置换重排
# =============================================================================
def make_jigsaw(images, perms):
    """
    把 batch 图像变成**打乱后的 9 块输入**。

    参数
    ----
    images : (B, 3, 96, 96)   演示用整图（论文是 225×225 再随机裁 64×64）
    perms  : 长度 B 的 list，每个是长度 9 的排列
             例如 perm = [2,0,1,3,4,5,6,7,8] 表示：
               网络输入槽 0 放**原格子 2**的图块
               网络输入槽 1 放**原格子 0**的图块
               ...

    返回
    ----
    patches : (B, 9, 3, 32, 32)  已打乱、可直接喂给 CFN
    """
    B = images.size(0)

    # --- 3.1 切成 3×3 不重叠块（每块 32×32）---
    # unfold(dim, size, step)：在 H/W 上滑窗
    # 结果 tiles 形状: (B, 3, 3, 3, 32, 32)
    #                   │  │  │  │
    #                   │  │  │  └─ 行方向 3 个格子
    #                   │  │  └──── 列方向 3 个格子（下一步 permute 后理顺）
    #                   │  └─────── 通道
    #                   └────────── batch
    tiles = images.unfold(2, 32, 32).unfold(3, 32, 32)

    # 调成 (B, 9, 3, 32, 32)：第 2 维按**行优先**展平 9 个格子
    # 原格子编号示意（与论文 3×3 网格一致）：
    #   0 1 2
    #   3 4 5
    #   6 7 8
    tiles = tiles.permute(0, 2, 3, 1, 4, 5).reshape(B, 9, 3, 32, 32)

    # --- 3.2 按每张图自己的置换，gather 重排第 1 维（格子维）---
    # idx[b] = perm，形状扩成与 tiles 可 broadcast，再 gather
    idx = torch.stack([torch.tensor(perms[b]) for b in range(B)])  # (B, 9)
    idx = idx.view(B, 9, 1, 1, 1).expand_as(tiles)
    # gather(dim=1)：输出槽 i ← 原格子 perm[i]
    return tiles.gather(1, idx)


# =============================================================================
# 4. 一轮完整训练（= 真实训练循环里的**一个 iteration**）
# =============================================================================
if __name__ == "__main__":

    # -------------------------------------------------------------------------
    # Step 0｜离线：构建置换集（训练前做一次，全程固定）
    # -------------------------------------------------------------------------
    # 论文用贪心最大化平均 Hamming 距离，避免置换彼此太像、任务太模糊。
    # 这里用随机排列演示；真实复现应换成论文 Algorithm 1。
    # perm_set[k] 的**下标 k**就是分类标签 y。
    perm_set = [torch.randperm(9).tolist() for _ in range(N_PERM)]
    # 例：perm_set[17] == [4, 1, 0, 8, 2, 5, 3, 7, 6]
    #     → 标签 y=17 表示**按这个顺序重排 9 块**

    # -------------------------------------------------------------------------
    # Step 1｜建模型与优化器
    # -------------------------------------------------------------------------
    model = CFN(feat_dim=32, n_perm=N_PERM)
    # 论文：SGD，无 BN，lr=0.01，batch=256，训约 350K iter
    opt = torch.optim.SGD(model.parameters(), lr=0.01)

    # -------------------------------------------------------------------------
    # Step 2｜取一个 mini-batch 图像（这里用随机张量代替真实 ImageNet）
    # -------------------------------------------------------------------------
    # 论文流水线更完整：
    #   resize 短边到 256 → 随机裁 225×225 → 分成 75×75 格
    #   → 每格内随机偏移取 64×64（制造间隙，防边缘连续捷径）
    #   → 每块独立均值/方差归一化、颜色抖动 / 灰度（防低层统计与色差捷径）
    # 本脚本省略防捷径细节，只保留**切块 + 置换**主路径。
    B = 4
    images = torch.randn(B, 3, 96, 96)

    # -------------------------------------------------------------------------
    # Step 3｜为每张图抽样一个置换索引，作为自监督标签
    # -------------------------------------------------------------------------
    # labels[b] ∈ {0, ..., N_PERM-1}，完全由数据增强决定，无需人工标注
    labels = torch.randint(0, N_PERM, (B,))
    # 取出对应的 9 元排列，供 make_jigsaw 打乱图块
    chosen_perms = [perm_set[int(labels[b])] for b in range(B)]

    # -------------------------------------------------------------------------
    # Step 4｜按置换生成网络输入
    # -------------------------------------------------------------------------
    # patches[b, i] = 原图第 chosen_perms[b][i] 号格子的内容
    patches = make_jigsaw(images, chosen_perms)  # (B, 9, 3, 32, 32)

    # -------------------------------------------------------------------------
    # Step 5｜前向：CFN 预测**这是哪一种打乱方式**
    # -------------------------------------------------------------------------
    model.train()
    logits = model(patches)  # (B, N_PERM)，第 j 维 ≈**置换 j**的得分

    # -------------------------------------------------------------------------
    # Step 6｜损失：多类交叉熵（代理任务 = N 类置换分类）
    # -------------------------------------------------------------------------
    # 论文式子直觉：p(S | F1..F9)，用分类逼近**配置 S 的后验**
    loss = F.cross_entropy(logits, labels)

    # -------------------------------------------------------------------------
    # Step 7｜反向传播 + 参数更新（标准一轮 SGD）
    # -------------------------------------------------------------------------
    opt.zero_grad()   # 清掉上一步残留梯度
    loss.backward()   # 九次 stem 前向的梯度累加到同一份 stem 权重
    opt.step()        # θ ← θ − lr · ∇θ L

    # -------------------------------------------------------------------------
    # Step 8｜（可选）看一眼这一步学得怎样
    # -------------------------------------------------------------------------
    # 真实训练会循环 Step2–7 数十万次；收敛后丢弃 fc7/fc8，
    # 把共享 stem（conv1–conv5）权重拷到标准 AlexNet 做检测/分类微调。
    pred = logits.argmax(dim=1)
    print("======== 一轮训练结束 ========")
    print("images  :", tuple(images.shape), "  # (B, C, H, W)")
    print("patches :", tuple(patches.shape), "  # (B, 9, C, h, w) 打乱后的九块")
    print("logits  :", tuple(logits.shape), f"  # (B, {N_PERM}) 对每个置换打分")
    print("labels  :", labels.tolist(), "  # 真正用的置换索引（自监督标签）")
    print("pred    :", pred.tolist(), "  # 网络当前猜测（随机初始化时接近乱猜）")
    print("loss    :", float(loss.detach()))
    print("例：第 0 张图的置换", chosen_perms[0],
          "→ 标签", int(labels[0]))
